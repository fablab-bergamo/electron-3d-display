"""Generate a seeded carbon point cloud from the existing atom sampler.

Run python3 tools/portal_atom_gen.py; --check verifies the generated asset.
The portal uses the sampled coordinates without loading Python in the browser.
"""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / 'pc'), str(ROOT / 'micropython')]
import micropython_shim  # noqa: E402,F401
import atom_cloud  # noqa: E402


def generate():
    xs, ys, zs, _, shells, _, _, _ = atom_cloud.build_atom_point_cloud(6, count=2400, seed=721)
    radii = sorted((x*x + y*y + z*z)**0.5 for x, y, z in zip(xs, ys, zs))
    radius = radii[int(len(radii) * 0.99)]
    points = [[round(x / radius, 5), round(y / radius, 5), round(z / radius, 5), n]
              for x, y, z, n in zip(xs, ys, zs, shells)]
    return '// Generated by tools/portal_atom_gen.py; do not edit.\nconst PortalAtomPoints = ' + json.dumps(points, separators=(',', ':')) + ';\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    path = ROOT / 'web/portal_atom_points.js'
    if args.check:
        if not path.exists() or path.read_text() != content:
            parser.exit(1, 'Regenerate portal atom points.\n')
    else:
        path.write_text(content)
    print('Portal atom asset is current.' if args.check else 'Generated portal carbon point cloud.')
